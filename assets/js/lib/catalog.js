/** Ilustracja dla dowolnej nazwy (bez kategorii): najpierw katalog, potem słowa kluczowe. */
export function guessIcon(name) {
    const n = normalize(name);
    if (!n)
        return null;
    const exact = CATALOG_BY_NAME.get(n);
    if (exact)
        return exact.icon;
    for (const [kw, ic] of KEYWORDS)
        if (n.includes(kw))
            return ic;
    return null;
}
/** Ilustracja produktu: zapisana ikona → zgadnięta z nazwy → ikona kategorii. */
export function productIcon(p, categoryName) {
    return p.icon || guessIcon(p.name) || categoryIcon(categoryName);
}
const CATALOG_BY_NAME = new Map(CATALOG.flatMap((g) => g.items.map((it) => [normalize(it.name), it])));
